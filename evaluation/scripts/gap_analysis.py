#!/usr/bin/env python3
"""
Gap Analysis Script
Analyzes GAPS.md and generates insights

Version: 1.0.0
Task: Anacron automation dependency

Usage:
    python gap_analysis.py --auto
    python gap_analysis.py --report
"""

import argparse
import re
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path


def analyze_gaps(gaps_file: Path) -> dict:
    """
    Analyze GAPS.md file and generate statistics.

    Returns:
        Dict with gap analysis results
    """
    if not gaps_file.exists():
        return {"error": "GAPS.md not found"}

    content = gaps_file.read_text()

    results = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "total_gaps": 0,
        "by_status": {},
        "by_priority": {},
        "by_category": {},
        "oldest_open": None,
        "recent_resolved": [],
        "stale_gaps": []
    }

    # Parse gap entries
    # Pattern: | GAP-XXX-NNN | Title | Priority | Module | Status |
    gap_pattern = r"\|\s*(GAP-([A-Z]+)-(\d+))\s*\|([^|]+)\|([^|]+)\|([^|]+)\|([^|]+)\|"

    for match in re.finditer(gap_pattern, content):
        gap_id = match.group(1)
        category = match.group(2)
        number = match.group(3)
        title = match.group(4).strip()
        priority = match.group(5).strip()
        module = match.group(6).strip()
        status = match.group(7).strip()

        results["total_gaps"] += 1

        # Count by status
        results["by_status"][status] = results["by_status"].get(status, 0) + 1

        # Count by priority
        results["by_priority"][priority] = results["by_priority"].get(priority, 0) + 1

        # Count by category
        results["by_category"][category] = results["by_category"].get(category, 0) + 1

    # Calculate statistics
    results["open_count"] = results["by_status"].get("Open", 0) + results["by_status"].get("In Progress", 0)
    results["resolved_count"] = results["by_status"].get("Resolved", 0)
    results["completion_rate"] = (
        results["resolved_count"] / results["total_gaps"] * 100
        if results["total_gaps"] > 0 else 0
    )

    return results


def generate_report(results: dict) -> str:
    """Generate gap analysis report."""
    if "error" in results:
        return f"Error: {results['error']}"

    report = f"""# Gap Analysis Report

**Generated:** {results['timestamp']}

## Summary

| Metric | Value |
|--------|-------|
| Total Gaps | {results['total_gaps']} |
| Open | {results['open_count']} |
| Resolved | {results['resolved_count']} |
| Completion Rate | {results['completion_rate']:.1f}% |

## By Status

| Status | Count |
|--------|-------|
"""
    for status, count in sorted(results['by_status'].items()):
        report += f"| {status} | {count} |\n"

    report += """
## By Priority

| Priority | Count |
|----------|-------|
"""
    for priority, count in sorted(results['by_priority'].items()):
        report += f"| {priority} | {count} |\n"

    report += """
## By Category

| Category | Count |
|----------|-------|
"""
    for category, count in sorted(results['by_category'].items(), key=lambda x: -x[1]):
        report += f"| {category} | {count} |\n"

    report += """
---
*Generated by gap_analysis.py v1.0.0*
"""
    return report


def main():
    parser = argparse.ArgumentParser(description="Gap Analysis Script")
    parser.add_argument("--auto", action="store_true", help="Auto mode for anacron")
    parser.add_argument("--report", action="store_true", help="Generate detailed report")
    parser.add_argument("--output", type=Path, help="Output file path")

    args = parser.parse_args()

    gaps_file = Path.home() / ".claude" / "GAPS.md"
    results = analyze_gaps(gaps_file)

    if args.report or args.auto:
        report = generate_report(results)

        if args.output:
            with open(args.output, 'w') as f:
                f.write(report)
            print(f"Report saved to: {args.output}")
        else:
            print(report)
    else:
        # Summary output for logging
        print(f"[GAP ANALYSIS] Total: {results.get('total_gaps', 0)}, "
              f"Open: {results.get('open_count', 0)}, "
              f"Resolved: {results.get('resolved_count', 0)}, "
              f"Rate: {results.get('completion_rate', 0):.1f}%")


if __name__ == "__main__":
    main()
